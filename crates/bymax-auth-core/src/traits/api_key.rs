//! The persistence port and value types for scoped service API keys (layer: traits).
//!
//! The host implements [`ApiKeyRepository`] against its own store, as it does for users.
//! Nothing stored here is reversible: a row carries the HMAC digest of the secret and never the
//! secret. Validity is decided by the library, not the store, so a revoked or expired row is
//! still returned by [`ApiKeyRepository::find_by_id`] and every refusal takes the same steps.

use async_trait::async_trait;
use time::OffsetDateTime;

use crate::RepositoryError;

/// One stored service key.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ApiKey {
    /// Row id, a lowercase UUID. It is the public half of the key a caller presents.
    pub id: String,
    /// Human name of the machine caller. NOT unique: several active keys may share one label,
    /// which is what makes an overlapping rotation possible.
    pub label: String,
    /// Lowercase hex HMAC-SHA-256 of the secret under the pepper, 64 characters.
    pub digest: String,
    /// The scopes this key holds. A route is admitted only when the key holds every scope it
    /// declares.
    pub scopes: Vec<String>,
    /// When the key was issued.
    pub created_at: OffsetDateTime,
    /// The key stops verifying at this instant, when set.
    pub expires_at: Option<OffsetDateTime>,
    /// When set, the key no longer verifies, whatever instant it holds.
    pub revoked_at: Option<OffsetDateTime>,
    /// The last time the key verified. Advisory and coalesced: see
    /// [`ApiKeyRepository::touch_last_used`].
    pub last_used_at: Option<OffsetDateTime>,
}

/// A stored key without its digest: what an operator-facing call may return or log.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ApiKeySummary {
    /// Row id.
    pub id: String,
    /// Human name of the machine caller.
    pub label: String,
    /// The scopes the key holds.
    pub scopes: Vec<String>,
    /// When the key was issued.
    pub created_at: OffsetDateTime,
    /// The key stops verifying at this instant, when set.
    pub expires_at: Option<OffsetDateTime>,
    /// When set, the key no longer verifies.
    pub revoked_at: Option<OffsetDateTime>,
    /// The last time the key verified (advisory).
    pub last_used_at: Option<OffsetDateTime>,
}

impl From<ApiKey> for ApiKeySummary {
    fn from(key: ApiKey) -> Self {
        Self {
            id: key.id,
            label: key.label,
            scopes: key.scopes,
            created_at: key.created_at,
            expires_at: key.expires_at,
            revoked_at: key.revoked_at,
            last_used_at: key.last_used_at,
        }
    }
}

/// The row a repository inserts: everything but the revocation and last-use fields, which start
/// empty.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct NewApiKey {
    /// Row id, generated by the library.
    pub id: String,
    /// Human name of the machine caller.
    pub label: String,
    /// Lowercase hex HMAC-SHA-256 of the secret under the pepper.
    pub digest: String,
    /// The scopes the key holds.
    pub scopes: Vec<String>,
    /// When the key was issued.
    pub created_at: OffsetDateTime,
    /// The key stops verifying at this instant, when set.
    pub expires_at: Option<OffsetDateTime>,
}

/// What a verified request carries: the stable handle and the authority of the key, never its
/// digest.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ApiKeyPrincipal {
    /// The key's row id: the stable handle to bucket a rate limit on after verification.
    pub id: String,
    /// The machine caller's label.
    pub label: String,
    /// The scopes the key holds.
    pub scopes: Vec<String>,
}

/// Persistence port for service API keys.
///
/// The library supplies `id` and `digest`; the store only persists them. Verification reads one
/// row per request, so [`ApiKeyRepository::find_by_id`] should be a primary-key lookup.
///
/// # Errors
///
/// Every method returns [`RepositoryError::Backend`] for a datastore failure. A row that cannot
/// be decoded is such a failure: it must surface as an error, never as a missing or lapsed key.
#[async_trait]
pub trait ApiKeyRepository: Send + Sync {
    /// Find a key by its row id. A revoked or expired row is still returned, and a missing one
    /// is `Ok(None)`.
    async fn find_by_id(&self, id: &str) -> Result<Option<ApiKey>, RepositoryError>;

    /// Insert a new key and return the stored row.
    async fn create(&self, row: NewApiKey) -> Result<ApiKey, RepositoryError>;

    /// Mark a key revoked as of `at`. `Ok(false)` when no such key exists; revoking a key that
    /// is already revoked is not an error.
    async fn mark_revoked(&self, id: &str, at: OffsetDateTime) -> Result<bool, RepositoryError>;

    /// Set when a key stops verifying, which rotation uses to retire the old key after an
    /// overlap. `Ok(false)` when no such key exists.
    async fn set_expiry(&self, id: &str, at: OffsetDateTime) -> Result<bool, RepositoryError>;

    /// Record when keys were last used, in one batch.
    ///
    /// MUST be monotonic: never move a `last_used_at` backwards (`GREATEST(last_used_at, :at)`,
    /// or a `WHERE last_used_at < :at` guard). Several instances flush independently, and a late
    /// flush from one must not overwrite a newer value written by another.
    async fn touch_last_used(
        &self,
        entries: &[(String, OffsetDateTime)],
    ) -> Result<(), RepositoryError>;

    /// List every key that carries `label`, active or not.
    async fn list_by_label(&self, label: &str) -> Result<Vec<ApiKey>, RepositoryError>;
}
